import random
import time

# Функция выбора персонажа
def choose_character():
    print("Выберите своего персонажа:")
    print("1. Гриб-мудрец (Большой белый гриб)")
    print("2. Гриб-целитель (Рыжий мухомор)")
    print("3. Гриб-охранник (Синеватый груздь)")
    print("4. Гриб-искатель (Подберёзовик)")
    print("5. Гриб-учитель (Лисичка)")
    
    choice = int(input("Введите номер вашего персонажа: "))
    
    if choice in [1, 2, 3, 4, 5]:
        return f"Вы выбрали {['Гриб-мудрец', 'Гриб-целитель', 'Гриб-охранник', 'Гриб-искатель', 'Гриб-учитель'][choice - 1]}"
    else:
        print("Некорректный выбор. Попробуйте снова.")
        return choose_character()

# Функция броска кубика
def roll_dice():
    return random.randint(1, 6)

# Функция для отслеживания здоровья
def track_health(points):
    return points

# Основная игра
def main_game():
    character = choose_character()
    print(f"Ты выбрал {character}.")

    # Начальное здоровье игрока и гриба
    player_health = 10
    enemy_health = 10

    # Логика игры...
    print("Начало приключения...")
    time.sleep(2)
    print("Ты стоишь посреди темного леса...")

    # Генерация случайного события
    event = random.choice([
        "Ты находишь магический кристалл!",
        "Тебя атакует злой гриб!",
        "Ты встречаешь старого друга-гриба.",
        "Ты находишь затерянную тропинку.",
        "Тебя приглашают на праздник грибов."
    ])

    # Отделение сообщений об изменениях событий
    print("\n".join([event, "-" * 20]))

    # Битва с грибом
    while enemy_health > 0:
        print("Ты видишь перед собой злого гриба!")
        
        # Описание битвы с злым грибом
        print("Гриб-охранник (Синеватый груздь):")
        print("Синеватый груздь, грозно возвышаясь над тобой, охраняет тропинку. Его синеватые шляпки сверкают в темноте, а длинные корни извиваются, словно щупальца. Он готов к бою!")
        print("Гриб-искатель (Подберёзовик):")
        print("Подберёзовик, погружённый в поиски чего-то важного, не замечает тебя. Его тёмно-коричневая шляпка блестит в свете луны, а длинные корни тянутся во все стороны, словно ища что-то в земле. Он готов к атаке!")
        print("Гриб-учитель (Лисичка):")
        print("Лисичка, окружённая светящимися грибами, учит других грибов. Она не ожидает нападения, но её магия может быть опасной. Её ярко-оранжевая шляпка мерцает в темноте, а вокруг кружатся маленькие светящиеся грибы, словно ученики.")

        # Выбор типа битвы
        print("Выбери тип битвы:")
        print("1. Физическая атака")
        print("2. Магическая атака")

        choice = int(input("Введи номер типа атаки: "))

        # Бросок кубика для физической атаки
        if choice == 1:
            print("Ты бросаешь кубик для физической атаки...")
            time.sleep(2)
            attack_roll = roll_dice()
            print(f"Твой бросок: {attack_roll}")

            # Описание результата атаки
            if attack_roll == 1:
                print("Гриб контратакует и наносит урон!")
                enemy_health += 2
                print(f"Твой текущий уровень здоровья: {track_health(player_health)}")
                print(f"Уровень здоровья гриба: {track_health(enemy_health)}")
            elif attack_roll == 6:
                print("Ты наносишь критический удар и побеждаешь гриба!")
                enemy_health = 0
                print(f"Твой текущий уровень здоровья: {track_health(player_health)}")
                print(f"Уровень здоровья гриба: {track_health(enemy_health)}")
            else:
                print("Ты успешно атакуешь гриба и наносишь урон.")
                enemy_health -= attack_roll
                print(f"Твой текущий уровень здоровья: {track_health(player_health)}")
                print(f"Уровень здоровья гриба: {track_health(enemy_health)}")

            # Бросок кубика для защиты гриба
            print("Гриб бросает кубик для защиты...")
            time.sleep(2)
            defense_roll = roll_dice()
            print(f"Защита гриба: {defense_roll}")

            # Определение результата битвы
            if defense_roll == 1:
                print("Гриб контратакует и наносит урон!")
                player_health -= 2
                print(f"Твой текущий уровень здоровья: {track_health(player_health)}")
                print(f"Уровень здоровья гриба: {track_health(enemy_health)}")
            elif defense_roll == 6:
                print("Гриб защищается и не получает урон.")
                print(f"Твой текущий уровень здоровья: {track_health(player_health)}")
                print(f"Уровень здоровья гриба: {track_health(enemy_health)}")
            else:
                print("Гриб получает урон.")
                player_health -= defense_roll
                print(f"Твой текущий уровень здоровья: {track_health(player_health)}")
                print(f"Уровень здоровья гриба: {track_health(enemy_health)}")

        # Бросок кубика для магической атаки
        elif choice == 2:
            print("Ты бросаешь кубик для магической атаки...")
            time.sleep(2)
            attack_roll = roll_dice()
            print(f"Твой бросок: {attack_roll}")

            # Описание результата атаки
            if attack_roll == 1:
                print("Твоя магия рассеивается, и гриб атакует тебя!")
                player_health -= 2
                print(f"Твой текущий уровень здоровья: {track_health(player_health)}")
                print(f"Уровень здоровья гриба: {track_health(enemy_health)}")
            elif attack_roll == 6:
                print("Ты используешь мощную магию и побеждаешь злого гриба!")
                enemy_health = 0
                print(f"Твой текущий уровень здоровья: {track_health(player_health)}")
                print(f"Уровень здоровья гриба: {track_health(enemy_health)}")
            else:
                print("Ты используешь магию и побеждаешь гриба.")
                enemy_health -= attack_roll
                print(f"Твой текущий уровень здоровья: {track_health(player_health)}")
                print(f"Уровень здоровья гриба: {track_health(enemy_health)}")

        # Проверка победы или поражения
        if player_health <= 0:
            print("Твой уровень здоровья опустился до нуля. Ты проиграл!")
        elif enemy_health <= 0:
            print("Гриб повержен! Ты победил!")
            print("Поздравляем! Вы прошли это испытание.")

    # Выбор действий игрока
    print("Что ты хочешь сделать?")
    print("1. Исследовать дальше")
    print("2. Вернуться назад")

    choice = int(input("Введи номер действия: "))

    if choice == 1:
        print("Ты продолжаешь свой путь...")
        time.sleep(2)
        print("Ты слышишь странные звуки впереди...")
        time.sleep(2)
        print("Ты видишь светящийся гриб, который может быть опасен или полезен...")
        time.sleep(2)
        main_game()
    elif choice == 2:
        print("Ты возвращаешься назад.")
        time.sleep(2)
        print("Ты замечаешь, что тропинка, по которой ты шёл, изменилась...")
        time.sleep(2)
        print("Ты видишь, что твой путь назад преграждает новый гриб...")
        time.sleep(2)
        main_game()
    else:
        print("Некорректный выбор. Попробуйте снова.")
        main_game()

# Запуск игры
if __name__ == "__main__":
    main_game()